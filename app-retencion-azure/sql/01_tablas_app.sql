-- Tablas propias de la aplicación (esquema G1). La app las crea sola al iniciar; este script es solo documentación.
-- No contiene datos ni claves.

IF OBJECT_ID('G1.APP_USUARIOS','U') IS NULL CREATE TABLE G1.APP_USUARIOS (usuario_id INT IDENTITY(1,1) PRIMARY KEY, usuario VARCHAR(50) NOT NULL UNIQUE, nombre VARCHAR(100) NOT NULL, correo VARCHAR(150) NULL, rol VARCHAR(20) NOT NULL CHECK (rol IN ('administrador','supervisor','agente')), clave_hash VARCHAR(255) NOT NULL, activo BIT NOT NULL DEFAULT 1, creado DATETIME2 NOT NULL DEFAULT SYSUTCDATETIME())
GO

IF COL_LENGTH('G1.APP_USUARIOS','debe_cambiar') IS NULL BEGIN ALTER TABLE G1.APP_USUARIOS ADD debe_cambiar BIT NOT NULL CONSTRAINT DF_APP_USR_dc DEFAULT 0; EXEC('UPDATE G1.APP_USUARIOS SET debe_cambiar=1 WHERE rol<>''administrador'''); END
GO

IF OBJECT_ID('G1.APP_SOLICITUDES','U') IS NULL CREATE TABLE G1.APP_SOLICITUDES (solicitud_id INT IDENTITY(1,1) PRIMARY KEY, nombre VARCHAR(100) NOT NULL, correo VARCHAR(150) NOT NULL, motivo VARCHAR(300) NULL, estado VARCHAR(12) NOT NULL DEFAULT 'pendiente', token CHAR(64) NOT NULL, creado DATETIME2 NOT NULL DEFAULT SYSUTCDATETIME(), resuelto DATETIME2 NULL, resuelto_por VARCHAR(50) NULL)
GO

IF OBJECT_ID('G1.APP_REPORTES_HIST','U') IS NULL CREATE TABLE G1.APP_REPORTES_HIST (fecha DATE NOT NULL PRIMARY KEY, clientes INT, activos INT, cancelados INT, tasa FLOAT, intervenciones INT, calificacion FLOAT)
GO

IF OBJECT_ID('G1.APP_ACTIVIDAD','U') IS NULL CREATE TABLE G1.APP_ACTIVIDAD (actividad_id INT IDENTITY(1,1) PRIMARY KEY, momento DATETIME2 NOT NULL DEFAULT SYSUTCDATETIME(), usuario VARCHAR(50) NOT NULL, accion VARCHAR(20) NOT NULL, entidad VARCHAR(30) NOT NULL, registro_id INT NULL)
GO
